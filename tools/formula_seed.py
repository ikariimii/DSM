"""Generate sql/seed/ref_formula_seed.sql from dam_safety.formulas.registry.REGISTRY.

Ownership (SCHEMA_CONTRACT §9): the DATA LAYER owns the formula registry. Version-bump rule: a change
to a formula's code, sources, description, output unit or test vectors needs a NEW formula_version
(never edit a released version - recomputes key on (formula_id, formula_version)). The fingerprint
column makes this enforceable: tests/test_formula_seed.py fails when the generated seed differs from
the committed one, and fails harder when a fingerprint changed under an existing version.
The app learns of a bump by reading ref.formula (new row, registered_ts) - no push channel.
Usage: python tools/formula_seed.py [--check]"""
import argparse
import hashlib
import inspect
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
from dam_safety.formulas import registry  # noqa: E402

OUT = os.path.join(ROOT, "sql", "seed", "ref_formula_seed.sql")


def fingerprint(f) -> str:
    try:
        code = inspect.getsource(f.fn)
    except (OSError, TypeError):
        code = repr(f.fn)
    blob = json.dumps([f.formula_id, f.version, f.reading_type, f.output_unit, f.description, list(f.sources),
                       list(f.test_vectors), code], sort_keys=True, default=str)
    return hashlib.sha256(blob.encode()).hexdigest()


def _q(s: str) -> str:
    """Spark SQL string literal: backslash-escape backslashes and single quotes."""
    return "'" + str(s).replace("\\", "\\\\").replace("'", "\\'") + "'"


def rows():
    for key in sorted(registry.REGISTRY):
        f = registry.REGISTRY[key]
        yield f, fingerprint(f)


def render() -> str:
    lines = ["-- GENERATED by tools/formula_seed.py from dam_safety.formulas.registry - do not edit by hand.",
             "-- Idempotent upsert of ref.formula. An existing (formula_id, formula_version) is never changed:",
             "-- WHEN MATCHED only refreshes code_ref if the fingerprint is identical (version-bump rule).",
             "USE CATALOG IDENTIFIER(:catalog);",
             "MERGE INTO ref.formula t USING (VALUES"]
    vals = []
    for f, fp in rows():
        vals.append("  (" + ", ".join([_q(f.formula_id), _q(f.version), _q(f.reading_type), _q(f.output_unit), _q(f.description),
                                       "array(" + ", ".join(_q(s) for s in f.sources) + ")",
                                       _q(json.dumps(list(f.test_vectors), sort_keys=True, default=str)),
                                       "true" if f.verified else "false", _q("dam_safety.formulas.registry#sha256=" + fp)]) + ")")
    lines.append(",\n".join(vals))
    lines += [") AS s(formula_id, formula_version, reading_type, output_unit, description, source_citation, test_vectors, verified, code_ref)",
              "ON t.formula_id = s.formula_id AND t.formula_version = s.formula_version",
              "WHEN MATCHED AND t.code_ref = s.code_ref THEN UPDATE SET t.verified = s.verified",
              "WHEN NOT MATCHED THEN INSERT (formula_id, formula_version, reading_type, output_unit, description, source_citation, test_vectors, verified, code_ref, registered_ts)",
              "  VALUES (s.formula_id, s.formula_version, s.reading_type, s.output_unit, s.description, s.source_citation, s.test_vectors, s.verified, s.code_ref, current_timestamp());",
              "-- Version-bump guard: a released (formula_id, formula_version) whose code fingerprint differs from the",
              "-- registry fails the deploy instead of being silently kept or overwritten.",
              "SELECT raise_error(concat('formula ', t.formula_id, ' ', t.formula_version, ' changed without a version bump'))",
              "FROM ref.formula t JOIN (VALUES",
              ",\n".join("  (" + _q(f.formula_id) + ", " + _q(f.version) + ", " + _q("dam_safety.formulas.registry#sha256=" + fp) + ")" for f, fp in rows()),
              ") AS s(formula_id, formula_version, code_ref)",
              "ON t.formula_id = s.formula_id AND t.formula_version = s.formula_version",
              "WHERE t.code_ref <> s.code_ref;",
              ""]
    return "\n".join(lines)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    new = render()
    if a.check:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        sys.exit(0 if cur == new else 1)
    open(OUT, "w").write(new)
    print(f"{sum(1 for _ in rows())} formulas -> {OUT}")
