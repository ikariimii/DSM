from __future__ import annotations

import copy
import hashlib
import hmac
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tests", "fixtures", "review_chain_signed_vector.json")
TEST_KEY = b"qa045c-public-test-key-NOT-A-SECRET"


class TestHmacSigner:
    """TEST ONLY. HMAC-SHA256 over the record_hash; verify also requires the matching key_id."""
    alg, key_id = "HMAC-SHA256-test", "k1"

    def sign(self, record_hash):
        return hmac.new(TEST_KEY, record_hash.encode("utf-8"), hashlib.sha256).hexdigest()

    def verify(self, record_hash, signature, key_id):
        return key_id == self.key_id and hmac.compare_digest(str(signature), self.sign(record_hash))


def base(n: int) -> dict:
    return {"review_id": f"rs-{n:04d}", "dam_id": "DAM-TEST-2", "subject_type": "alarm_event", "subject_id": f"ep-{n}",
            "review_level": "engineer", "decision": "acknowledge", "comment": f"synthetic ack {n}",
            "reviewer_id": "eng.s@example.org", "reviewer_pe_license": None,
            "signed_ts": f"2026-11-09T15:0{n}:00.000000+00:00", "signature_hash": f"{n:x}" * 64,
            "action_type": "alarm_ack", "reviewer_email": "eng.s@example.org", "reviewer_sub": "sub-s",
            "original_value": "{}", "corrected_value": "{}"}


def cases(rows: list[dict], head: dict, signer) -> dict:
    """name -> (rows, head) mutations; every mutation is synthetic."""
    def mut(fn):
        r = copy.deepcopy(rows)
        fn(r)
        return r
    clear = lambda r: r.update(signature=None, sig_alg=None, key_id=None)  # noqa: E731
    out = {
        "intact": (rows, head),
        "stripped_first": (mut(lambda r: clear(r[0])), head),
        "stripped_all": (mut(lambda r: [clear(x) for x in r]), head),
        "downgrade_seq2": (mut(lambda r: clear(r[1])), head),
        "downgrade_key_id_only": (mut(lambda r: r[2].update(key_id="")), head),
        "forged_signature": (mut(lambda r: r[1].update(signature="0" * 64)), head),
        "signature_of_other_record": (mut(lambda r: r[1].update(signature=r[0]["signature"])), head),
        "bad_sig_alg_none": (mut(lambda r: r[1].update(sig_alg="none")), head),
        "bad_sig_alg_unknown": (mut(lambda r: r[0].update(sig_alg="RS256")), head),
        "wrong_key_id": (mut(lambda r: r[1].update(key_id="k2")), head),
        "truncated_tail": (rows[:2], head),
        "truncated_tail_and_head_rewound_wrong_hash": (rows[:2], {**head, "chain_seq": 2}),
        "head_altered_hash": (rows, {**head, "head_hash": "f" * 64}),
        "reordered_seq_swap": (mut(lambda r: (r[1].update(chain_seq=3), r[2].update(chain_seq=2))), head),
        "replayed_duplicate_seq2": (rows + [copy.deepcopy(rows[1])], head),
        "replayed_seq1_as_seq4": (rows + [{**copy.deepcopy(rows[0]), "chain_seq": 4,
                                           "prev_hash": rows[2]["record_hash"]}],
                                  {**head, "chain_seq": 4}),
    }
    return out


def main() -> None:
    sys.path.insert(0, os.path.join(ROOT, "app"))
    from backend import audit_chain as app_ac  # noqa: E402  (read only)
    from backend.repos.state import StateStore  # noqa: E402  (read only)
    signer = TestHmacSigner()
    st = StateStore("sqlite")
    for n in range(1, 4):
        st.append_chained("DAM-TEST-2", app_ac.GENESIS, app_ac.finalizer(base(n), signer))
    rows = [{k: r[k] for k in (*app_ac.CHAIN_FIELDS, *app_ac.HASH_EXCLUDED)} for r in st.chain_rows("DAM-TEST-2")]
    h = st.chain_head("DAM-TEST-2")
    head = {"chain_id": h["chain_id"], "chain_seq": int(h["chain_seq"]), "head_hash": h["head_hash"]}
    vec = {"_comment": "Synthetic signed interop vector, generated by tools/gen_review_chain_signed_vector.py with the "
                       "App Developer's app/backend/audit_chain.py + repos/state.py (read only). TEST-ONLY HMAC key "
                       "(public, see generator). expected = the app's verify_chain verdict. No real data.",
           "signer": {"alg": TestHmacSigner.alg, "key_id": TestHmacSigner.key_id, "key_utf8": TEST_KEY.decode()},
           "rows": rows, "head": head, "cases": {}}
    for name, (rws, hd) in cases(rows, head, signer).items():
        v = app_ac.verify_chain(copy.deepcopy(rws), hd, signer)
        n = app_ac.verify_chain(copy.deepcopy(rws), hd, app_ac.NoopSigner())  # app default (no real signer)
        vec["cases"][name] = {"rows": rws, "head": hd,
                              "expected": {"ok": v["ok"], "reason": v["reason"],
                                           "first_broken_seq": v["first_broken_seq"]},
                              "expected_noop_signer": {"ok": n["ok"], "reason": n["reason"],
                                                       "first_broken_seq": n["first_broken_seq"]}}
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(vec, f, indent=1, ensure_ascii=False)
        f.write("\n")
    for name, c in vec["cases"].items():
        print(f"{name:45s} {c['expected']}  noop: {c['expected_noop_signer']}")


if __name__ == "__main__":
    main()
