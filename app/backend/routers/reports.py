"""DSSMR (Dam Safety Surveillance and Monitoring Report) draft generation.

The draft is a starting point for the engineer of record: it summarizes only
values that passed the display gate, states explicitly how many values were
withheld and why, and leaves the evaluation/sign-off sections for the engineer."""
from __future__ import annotations

from collections import Counter
from datetime import datetime, timezone

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel

from ..common import LEVEL_NAMES, gate_for, merge_ack, site_or_404
from ..deps import Ctx, analytics, ctx, require, store
from ..verify import INCL_KEYS

router = APIRouter(prefix="/api/dams/{dam_id}/reports")


class ReportBody(BaseModel):
    period_start: str  # ISO date or timestamp, UTC
    period_end: str


def _iso(d: str, end: bool = False) -> str:
    try:
        if len(d) == 10:
            datetime.strptime(d, "%Y-%m-%d")
            return d + ("T23:59:59Z" if end else "T00:00:00Z")
        datetime.fromisoformat(d.replace("Z", "+00:00"))
        return d
    except ValueError as e:
        raise HTTPException(422, f"bad date {d!r}") from e


def _fmt(v, nd=3):
    return "—" if v is None else f"{v:.{nd}f}"


def build_dssmr(an, st, dam_id: str, start: str, end: str, author: str) -> str:
    site = site_or_404(an, dam_id)
    gate = gate_for(an, dam_id)
    insts = an.instruments(dam_id)
    lines = [
        f"# DRAFT — Dam Safety Surveillance and Monitoring Report (DSSMR)",
        "",
        f"**{site['name']}** ({dam_id}) · NID {site.get('nid_id', '—')} · hazard: {site.get('hazard_class', '—')} · "
        f"type: {site.get('dam_type', '—')}",
        "",
        f"Reporting period: {start} to {end} (UTC). Generated {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC by {author}.",
        "",
        "> DRAFT generated by the Dam Safety app. Not reviewed. Values shown are limited to readings whose "
        "formula version is engine-verified, whose calibration is approved, and which are not QC-flagged BAD. "
        "Withheld values are counted per instrument below. The engineer of record must complete the evaluation "
        "and sign-off sections.",
        "",
        "## 1. Instrumentation summary",
        "",
        "| Instrument | Type | Unit | Cal. version(s) | n | shown | withheld (reason) | QC flags | min | max | last shown |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    withheld_total = 0
    for i in insts:
        if i["instrument_type"] == "inclinometer":
            continue
        rows = gate.apply_all(an.readings(i["instrument_id"], start, end))
        shown = [r for r in rows if r["display_status"] == "VERIFIED" and r.get("corrected_value") is not None]
        wh = Counter(r["display_status"] for r in rows if r["display_status"] != "VERIFIED")
        withheld_total += sum(wh.values())
        qa = Counter(r.get("qa_flag") for r in rows)
        vals = [r["corrected_value"] for r in shown]
        unit = (rows[0].get("corrected_unit") or rows[0].get("eng_unit")) if rows else i["eng_unit"]
        cv = ", ".join(sorted({f"v{r['cal_version']}" for r in rows if r.get("cal_version") is not None})) or "—"
        lines.append(
            f"| {i['instrument_id']} | {i['instrument_type']} | {unit} | {cv} | {len(rows)} | {len(shown)} | "
            f"{', '.join(f'{k}: {v}' for k, v in wh.items()) or '0'} | "
            f"{', '.join(f'{k}: {v}' for k, v in qa.items()) or '—'} | "
            f"{_fmt(min(vals) if vals else None)} | {_fmt(max(vals) if vals else None)} | "
            f"{_fmt(vals[-1] if vals else None)} |")
    lines += ["", f"Total withheld values in period: **{withheld_total}**.", ""]

    incl = [i for i in insts if i["instrument_type"] == "inclinometer"]
    if incl:
        lines += ["## 2. Inclinometers", "",
                  "| Hole | Last survey in period | Cal. version | Max cumulative A (mm) | Max resultant (mm) | "
                  "Checksum QC | Status |", "|---|---|---|---|---|---|---|"]
        for i in incl:
            sv = [s for s in an.incl_surveys(i["instrument_id"]) if start <= s["survey_ts"] <= end]
            if not sv:
                lines.append(f"| {i['instrument_id']} | none | — | — | — | — | no survey in period |")
                continue
            last = sv[-1]
            rows = gate.apply_all(an.incl_profile(i["instrument_id"], last["survey_id"]), INCL_KEYS)
            ok = all(r["display_status"] == "VERIFIED" for r in rows)
            qa = Counter(r.get("qa_flag") for r in rows)
            ma = max((abs(r["a_cum_mm"]) for r in rows), default=None) if ok else None
            mr = max((r["resultant_mm"] for r in rows), default=None) if ok else None
            lines.append(f"| {i['instrument_id']} | {last['survey_ts']} | v{rows[0].get('cal_version')} | "
                         f"{_fmt(ma, 1)} | {_fmt(mr, 1)} | {', '.join(f'{k}: {v}' for k, v in qa.items())} | "
                         f"{'shown' if ok else 'withheld: ' + rows[0]['display_status']} |")
        lines += ["", "Bias-shift corrections are not applied or proposed in this draft (pending the QA-020 specification and engine support).", ""]

    events = [e for e in an.alarm_events([dam_id]) if start <= e["event_ts"] <= end]
    events = merge_ack([gate.apply_event(e) for e in events], st.ack_states([e["event_id"] for e in events]))
    lines += [f"## {3 if incl else 2}. Threshold exceedances and alarms", ""]
    if events:
        lines += ["| Event | Time (UTC) | Instrument | Level | Value | Limit | PFM | State |",
                  "|---|---|---|---|---|---|---|---|"]
        for e in sorted(events, key=lambda x: x["event_ts"]):
            val = "withheld (unverified)" if e["value"] is None and e.get("rule") != "no_data" else _fmt(e["value"])
            lines.append(f"| {e['event_id']} | {e['event_ts']} | {e['instrument_id']} | L{e['level']} "
                         f"{LEVEL_NAMES.get(e['level'], '')} | {val} {e.get('unit') or ''} | "
                         f"{_fmt(e.get('limit'))} | {', '.join(e.get('pfm_ids') or [])} | {e['state']} |")
    else:
        lines.append("No alarm events in the period.")
    lines += ["", f"## {4 if incl else 3}. Potential failure modes", ""]
    reviews = st.pfm_reviews(dam_id)
    for p in an.pfms(dam_id):
        r = next((x for x in reviews if x["pfm_id"] == p["pfm_id"]), None)
        lines.append(f"- **{p['pfm_id']}** ({p.get('pfm_code')}; Ch.17 {p.get('ch17_disposition') or 'n/a'}, "
                     f"legacy Ch.14 category {p.get('legacy_ch14_category') or 'n/a'}, {p.get('loading_condition') or 'n/a'} "
                     f"loading): {p.get('description')}. Monitored by "
                     f"{', '.join(p.get('instruments') or [])}. Last review: "
                     f"{r['reviewed_at'] + ' by ' + r['reviewed_by'] + ' (' + r['status'] + ')' if r else 'none recorded'}.")
    n = 5 if incl else 4
    lines += ["", f"## {n}. Engineer's evaluation", "", "_To be completed by the engineer of record._", "",
              f"## {n + 1}. Conclusions and recommendations", "", "_To be completed._", "",
              f"## {n + 2}. Sign-off", "", "| Role | Name | Date |", "|---|---|---|",
              "| Engineer of record | | |", "| Dam safety officer | | |", ""]
    return "\n".join(lines)


@router.post("")
def create(dam_id: str, body: ReportBody, c: Ctx = Depends(ctx), an=Depends(analytics), st=Depends(store)):
    require(c, dam_id, "engineer")
    start, end = _iso(body.period_start), _iso(body.period_end, end=True)
    if start > end:
        raise HTTPException(422, "period_start is after period_end")
    md = build_dssmr(an, st, dam_id, start, end, c.email)
    rep = st.save_report(dam_id, start, end, c.email, md)
    st.audit(c.email, "report_draft", dam_id, rep["report_id"], {"period": [start, end]})
    return rep


@router.get("")
def list_reports(dam_id: str, c: Ctx = Depends(ctx), st=Depends(store)):
    require(c, dam_id)
    return {"reports": st.list_reports(dam_id)}


@router.get("/{report_id}")
def get_report(dam_id: str, report_id: str, c: Ctx = Depends(ctx), st=Depends(store)):
    require(c, dam_id)
    rep = st.get_report(report_id)
    if rep is None or rep["dam_id"] != dam_id:
        raise HTTPException(404, "Unknown report")
    return rep
